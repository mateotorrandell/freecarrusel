export type StringKey = keyof (typeof STRINGS)["es"];

const CACHE_KEY = "oc-language";

/** Read the persisted language synchronously so the first paint isn't in the wrong language. */
function readCached(): Language {
  if (typeof window === "undefined") return DEFAULT_SETTINGS.language;
  const v = window.localStorage.getItem(CACHE_KEY);
  return v === "es" || v === "en" ? v : DEFAULT_SETTINGS.language;
}

/**
 * Language + translator. Seeds from localStorage for an instant correct paint,
 * then reconciles with the server (which is the source of truth the agent reads).
 */
export function useLanguage() {
  const [language, setLanguageState] = useState<Language>(readCached);

  useEffect(() => {
    fetch("/api/settings")
      .then((r) => r.json())
      .then((s: { language?: Language }) => {
        if (s.language && s.language !== language) {
          setLanguageState(s.language);
          window.localStorage.setItem(CACHE_KEY, s.language);
        }
      })
      .catch(() => {});
    // Intentionally only on mount — later changes go through setLanguage.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  const setLanguage = useCallback(async (next: Language) => {
    setLanguageState(next);
    window.localStorage.setItem(CACHE_KEY, next);
    await fetch("/api/settings", {
      method: "PUT",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ language: next }),
    }).catch(() => {});
  }, []);

  const t = useCallback(
    (key: StringKey) => STRINGS[language][key] ?? STRINGS.en[key],
    [language]
  );

  return { language, setLanguage, t };
}
